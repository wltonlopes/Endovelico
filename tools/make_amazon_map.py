def make_preview(heights, tiles, palette, size):
    """Coloured top-down preview in the style of the vanilla map previews."""
    from PIL import Image
    colours = {
        "tropic_cliff_grass": (98, 110, 62), "tropic_plants": (70, 104, 46),
        "tropic_grass_c": (86, 118, 52), "tropic_grass_plants": (78, 112, 48),
        "tropic_dirt_a": (132, 112, 76), "tropic_beach_dry": (176, 156, 112),
        "tropic_dirt_a_plants": (112, 108, 64), "tropic_cliff_a": (110, 98, 78),
    }
    img = Image.new("RGB", (size, size))
    px = img.load()
    for x in range(size):
        for y in range(size):
            h = float(heights[x * size + y])
            if h < -1:
                d = min(1.0, (-h) / 20)
                c = (int(96 - 50 * d), int(84 - 40 * d), int(52 - 22 * d))
            else:
                c = colours.get(palette[int(tiles[x * size + y])], (90, 110, 60))
                shade = 0.85 + 0.03 * h
                c = tuple(max(0, min(255, int(v * shade))) for v in c)
            # rotate so that the preview matches the in-game minimap orientation
            px[x, size - 1 - y] = c
    out = MOD / "art/textures/ui/session/icons/mappreview/amazon.png"
    img.resize((512, 512), Image.BICUBIC).save(out)
    return out


def main():
    text = SRC.read_text()
    heights = read_array(text, "getHeightMap")
    tiles = read_array(text, "getTileMap")
    palette = [p.strip().strip('"') for p in read_array(text, "getTilePallet")]
    size = int(round(len(heights) ** 0.5))
    assert size * size == len(heights) == len(tiles)
    assert max(int(t) for t in tiles) < len(palette)

    js = (SCRIPT
          .replace("__HM_SIZE__", str(size))
          .replace("__H_MIN__", str(H_MIN))
          .replace("__H_MAX__", str(H_MAX))
          .replace("__ALPHABET__", ALPHABET)
          .replace("__PALETTE__", json.dumps(palette))
          .replace("__HEIGHTMAP__", chunked(encode_heights(heights)))
          .replace("__TILEMAP__", chunked(encode_tiles(tiles))))
    (MOD / "maps/random/amazon.js").write_text(js)

    settings = {
        "settings": {
            "Name": "Amazon",
            "Script": "amazon.js",
            "Description": "Players are transported into the tropics, to the mouth of the great Amazon, arguably the longest and largest river in the world. Peccaries, tapirs, monkeys and caimans share the rainforest with jaguars and boas. Will you triumph and take control of this tropical paradise, or will you be trampled into the dust by ruthless and ambitious enemies?",
            "Keywords": [],
            "Preview": "amazon.png",
            "CircularMap": False,
        }
    }
    (MOD / "maps/random/amazon.json").write_text(json.dumps(settings, indent="\t") + "\n")
    print("written maps/random/amazon.js / .json, preview:", make_preview(heights, tiles, palette, size))


if __name__ == "__main__":
    main()

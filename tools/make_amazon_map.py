# 64 characters that need no escaping inside a JS string
ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"
H_MIN, H_MAX = -20.0, 7.0
LEVELS = 64 * 64 - 1


def read_array(text, func):
    m = re.search(func + r"\(\)\s*\{\s*return \[([^\]]*)\]", text)
    return [v.strip() for v in m.group(1).split(",") if v.strip()]


def encode_heights(values):
    out = []
    for v in values:
        q = round((float(v) - H_MIN) / (H_MAX - H_MIN) * LEVELS)
        out.append(ALPHABET[q // 64] + ALPHABET[q % 64])
    return "".join(out)


def encode_tiles(values):
    return "".join(ALPHABET[int(v)] for v in values)


def chunked(s, width=200):
    """Split a long string literal over several lines."""
    parts = [s[i:i + width] for i in range(0, len(s), width)]
    return "\n\t\t\"" + "\" +\n\t\t\"".join(parts) + "\""



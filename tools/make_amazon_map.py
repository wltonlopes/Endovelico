#!/usr/bin/env python3
"""Port the old (Alpha 21) "Amazon" random map to the 0 A.D. 0.29 map API.

  python3 tools/make_amazon_map.py [~/Downloads/amazon.js]

The old script carries the heightmap, the terrain tilemap and the terrain
palette as huge inline arrays. They are re-encoded as compact strings and the
map logic is rewritten for the current rmgen/rmgen2 libraries, using this
mod's "generic/amazon" biome and its Amazonian fauna. Writes:
  maps/random/amazon.js, maps/random/amazon.json
  art/textures/ui/session/icons/mappreview/amazon.png
"""

